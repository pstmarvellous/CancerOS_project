import { expect, test } from '@playwright/test';
import { mkdirSync } from 'node:fs';

const base = process.env.PRODUCT_VIEWER_BASE_URL ?? 'http://127.0.0.1:3000';
const output = 'docs/engineering/testing/product-workspace';
test.use({ actionTimeout: 15000 });

test('large 3D workspace: panels, maximize, direct camera, native fullscreen and retained state', async ({ page, context }) => {
  test.setTimeout(180000);
  await context.clearCookies();
  await page.setViewportSize({ width: 1920, height: 1080 });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(`${base}/demo?view=twin&scenario=SC-01`);
  const viewer = page.locator('section[aria-label="Selected digital twin"]');
  const canvas = viewer.locator('canvas[data-render-ready="true"]');
  await expect(canvas).toBeVisible({ timeout: 60000 });
  const normal = (await canvas.boundingBox())!;
  expect(normal.height).toBeGreaterThan(600);
  expect(normal.width).toBeGreaterThan(1000);
  await page.getByRole('button', { name: 'Collapse navigation', exact: true }).click();
  await expect(page.getByRole('navigation', { name: 'Demo workspace' })).toBeHidden();
  await viewer.getByRole('button', { name: 'Collapse measurements', exact: true }).click();
  await expect(page.locator('#demo-measurements')).toBeHidden();
  await expect.poll(async () => (await canvas.boundingBox())!.width).toBeGreaterThan(normal.width);
  await viewer.getByRole('button', { name: 'Next state →', exact: true }).click();
  await expect(page.getByTestId('demo-volume')).toHaveText('64 mm³');
  const selected = new URL(page.url()).searchParams.get('state')!;
  await viewer.getByRole('button', { name: 'Maximize viewer', exact: true }).click();
  await expect(viewer).toHaveAttribute('data-maximized', 'true');
  await expect.poll(async () => (await canvas.boundingBox())!.height).toBeGreaterThan(1080 * 0.6);
  await expect(canvas).toHaveAttribute('data-selected-annotation', selected);
  const box = (await canvas.boundingBox())!;
  const drag = async () => {
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width / 2 + 70, box.y + box.height / 2 + 30, { steps: 8 });
    await page.mouse.up();
  };
  let before = await canvas.getAttribute('data-camera-state');
  await drag();
  await expect(canvas).not.toHaveAttribute('data-camera-state', before!);
  await viewer.getByRole('button', { name: 'Pan', exact: true }).click();
  before = await canvas.getAttribute('data-camera-state');
  await drag();
  await expect(canvas).not.toHaveAttribute('data-camera-state', before!);
  before = await canvas.getAttribute('data-camera-state');
  await page.mouse.wheel(0, -180);
  await expect(canvas).not.toHaveAttribute('data-camera-state', before!);
  const viewport = viewer.getByRole('group', { name: 'Interactive 3D viewport' });
  await viewport.focus();
  before = await canvas.getAttribute('data-camera-state');
  await page.keyboard.press('Shift+ArrowRight');
  await expect(canvas).not.toHaveAttribute('data-camera-state', before!);
  await viewer.getByRole('button', { name: 'Reset view', exact: true }).click();
  mkdirSync(output, { recursive: true });
  await page.screenshot({ path: `${output}/01-maximized-3d.png` });
  await viewer.getByRole('button', { name: 'Restore layout', exact: true }).click();
  await expect(viewer).not.toHaveAttribute('data-maximized', 'true');
  expect(new URL(page.url()).searchParams.get('state')).toBe(selected);
  await page.getByRole('button', { name: 'Expand navigation', exact: true }).click();
  await viewer.getByRole('button', { name: 'Show measurements', exact: true }).click();
  await expect(page.getByTestId('demo-volume')).toHaveText('64 mm³');
  const nativeFullscreenSupported = await page.evaluate(() => document.fullscreenEnabled);
  if (nativeFullscreenSupported) {
    await viewer.getByRole('button', { name: 'Fullscreen', exact: true }).click();
    await expect.poll(() => page.evaluate(() => document.fullscreenElement?.getAttribute('aria-label'))).toBe('Selected digital twin');
    await viewer.getByRole('button', { name: 'Next state →', exact: true }).click();
    await expect(canvas).not.toHaveAttribute('data-selected-annotation', selected);
    await page.screenshot({ path: `${output}/02-native-fullscreen.png` });
    await viewer.getByRole('button', { name: 'Exit fullscreen', exact: true }).click();
    await expect.poll(() => page.evaluate(() => document.fullscreenElement === null)).toBe(true);
    await expect(page.getByTestId('demo-volume')).toHaveText('8 mm³');
  }
  test.info().annotations.push({ type: 'native-fullscreen', description: nativeFullscreenSupported ? 'Native enter, timeline selection and exit verified.' : 'Fullscreen API unavailable in this browser; maximize verified.' });
  await page.locator('#demo-scenario').selectOption('SC-03');
  await expect(page.getByTestId('demo-volume')).toHaveText('216 mm³');
  await viewer.getByRole('button', { name: 'Next state →', exact: true }).click();
  await expect(page.getByTestId('demo-volume')).toHaveText('343 mm³');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${output}/02-large-workspace.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(canvas).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `${output}/03-responsive-viewer.png`, fullPage: true });
  expect(errors).toEqual([]);
});
