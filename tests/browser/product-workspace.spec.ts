test('anonymous, viewer, outsider and cross-origin requests cannot write research records',async({request})=>{
  const data=fixture();
  expect((await request.get(`${base}/api/research-cases?project=${data.project_id}`)).status()).toBe(401);
  expect((await request.post(`${base}/api/research-session`,{headers:{origin:'https://untrusted.example'},data:{token:data.admin_token}})).status()).toBe(403);
  expect((await request.post(`${base}/api/research-session`,{headers:{origin:base},data:{token:data.viewer_token}})).status()).toBe(200);
  expect((await request.post(`${base}/api/research-cases?project=${data.project_id}`,{headers:{origin:base,'idempotency-key':'viewer-denial'},data:{source_version_id:data.source_version_id,case_identifier:'DENIED',title:'Denied',pseudonym:'Denied',profile_source_reference:'Artificial test'}})).status()).toBe(403);
  expect((await request.post(`${base}/api/research-session`,{headers:{origin:base},data:{token:data.outsider_token}})).status()).toBe(200);
  expect((await request.get(`${base}/api/research-cases?project=${data.project_id}`)).status()).toBe(404);
});
