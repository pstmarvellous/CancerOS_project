import { expect, test, type Page } from '@playwright/test';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const bundle = '.local/phase3-browser-fixture.json';
test.use({actionTimeout: 15000});
async function token(page: Page, value: string) {
  // Keep ephemeral credentials out of locator diagnostics and exported evidence.
  await page.evaluate(secret => {
    const input = document.querySelector<HTMLInputElement>('input[type=password]')!;
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(input, secret);
    input.dispatchEvent(new Event('input', {bubbles:true}));
  }, value);
}

test('private published simulation timeline, actual geometry, trends and exact fusion', async ({page}) => {
  test.setTimeout(180000);
  test.slow();
  expect(existsSync(bundle), 'Start the explicitly disposable Phase 3 browser fixture').toBe(true);
  const fixture = JSON.parse(readFileSync(bundle, 'utf8'));
  await page.goto('http://127.0.0.1:3000/simulation');
  await page.getByLabel('Project UUID', {exact:true}).fill(fixture.project_id);
  await page.getByLabel('Patient UUID', {exact:true}).fill(fixture.patient_id);
  await page.getByLabel('Branch UUID', {exact:true}).fill(fixture.branch_id);
  await token(page, fixture.token);
  const loadBranch = page.getByRole('button', {name:'Load baseline branch',exact:true});
  await loadBranch.focus(); await expect(loadBranch).toBeFocused();
  await loadBranch.press('Enter');
  await expect(page.getByRole('status').filter({hasText:'Branch loaded.'})).toBeVisible({timeout: 90000});
  await page.getByLabel('Saved configuration UUID (optional)', {exact:true}).fill(fixture.config_id);
  await page.getByRole('button', {name:'Load saved configuration',exact:true}).click();
  await expect(page.getByRole('textbox', {name:'Simulation configuration JSON',exact:true})).toHaveValue(/SC-01/, {timeout: 90000});
  await page.getByRole('button', {name:'Inspect eligibility and schedule',exact:true}).click();
  await expect(page.getByRole('table', {name:'Server sampled schedule · relative days, not calendar dates',exact:true})).toBeVisible({timeout: 90000});
  await expect(page.getByRole('button', {name:'Publish complete run privately',exact:true})).toBeDisabled();
  await page.goto('http://127.0.0.1:3000/timeline');
  await page.getByLabel('Project UUID', {exact:true}).fill(fixture.project_id);
  await page.getByLabel('Patient UUID', {exact:true}).fill(fixture.patient_id);
  await token(page, fixture.token);
  await page.getByRole('combobox', {name:'Observation context',exact:true}).selectOption('simulation');
  await page.getByLabel('Exact data revision', {exact:true}).fill(String(fixture.data_revision));
  await page.getByLabel('Knowledge as of (ISO timestamp with timezone)', {exact:true}).fill(fixture.knowledge_as_of);
  await page.getByLabel('Branch UUID', {exact:true}).fill(fixture.branch_id);
  await page.getByLabel('Run UUID', {exact:true}).fill(fixture.run_id);
  await page.getByLabel('Published completion UUID', {exact:true}).fill(fixture.completion_id);
  const response = page.waitForResponse(r => r.url().endsWith('/timeline-queries'));
  await page.getByRole('button', {name:'Load exact timeline', exact:true}).click();
  const timelineResponse = await response; expect(timelineResponse.status()).toBe(200);
  const timeline = await timelineResponse.json();
  const physical = timeline.items.filter((p: {geometry_result_id: string|null}) => p.geometry_result_id);
  expect(physical.length).toBe(3);
  expect(physical.map((p: {exact_value:string}) => p.exact_value)).toEqual(fixture.expected_followup_values);
  const first = physical[0];
  await page.getByRole('button', {name:`Inspect ${first.id.slice(0,8)}`, exact:true}).click();
  const canvas = page.locator('canvas[data-render-ready]');
  await expect(canvas).toHaveAttribute('data-render-ready', 'true', {timeout: 90000});
  await expect(page.getByText(/Exact selected synthetic region/)).toBeVisible();
  const camera = await canvas.getAttribute('data-camera-state');
  await page.getByRole('button', {name:'Rotate left', exact:true}).click();
  await expect(canvas).not.toHaveAttribute('data-camera-state', camera!);
  const fusionResponse = page.waitForResponse(r => r.url().endsWith('/fusion-queries'));
  await page.getByRole('button', {name:'Load exact state overview', exact:true}).click();
  const fusionReply = await fusionResponse; expect(fusionReply.status()).toBe(200);
  const fusion = await fusionReply.json();
  expect(first.state_ids).toContain(fusion.canonical_state.snapshot.id);
  await expect(page.getByRole('region', {name:'Retained state fusion context', exact:true})).toBeVisible();
  await expect(page.getByRole('region', {name:'Missing state evidence', exact:true})).toContainText('source_note_extraction_unavailable');
  const trendsResponse = page.waitForResponse(r => r.url().endsWith('/trend-queries'));
  await page.getByRole('button', {name:'Load descriptive trends for this window', exact:true}).click();
  const trendsReply = await trendsResponse; expect(trendsReply.status()).toBe(200);
  const trends = await trendsReply.json();
  const expectedVolumes = [fixture.expected_volume_mm3, ...fixture.expected_followup_values].join(',');
  const volumes = trends.series.find((s: {points:{exact_value:string}[]}) => s.points.map(p => p.exact_value).join(',') === expectedVolumes);
  expect(volumes).toBeTruthy();
  expect(volumes.points.map((p: {x_elapsed_days:string}) => p.x_elapsed_days)).toEqual(['0','37','56','90']);
  expect(volumes.endpoint.absolute_change).toBe('-215');
  expect(volumes.endpoint.percentage_change).toBe('-99.537037037');
  await page.getByRole('combobox', {name:'Trend metric and source context',exact:true}).selectOption(volumes.key);
  await expect(page.getByRole('img', {name:/numerical_region_volume observations on elapsed-time axis/})).toBeVisible();
  await expect(page.getByText('-99.537037037%', {exact:true})).toBeVisible();
  const clinical = timeline.items.find((p: {geometry_result_id:string|null; modality:string}) => !p.geometry_result_id && p.modality !== 'imaging');
  expect(clinical).toBeTruthy();
  await page.getByRole('button', {name:`Inspect ${clinical.id.slice(0,8)}`, exact:true}).click();
  await expect(canvas).toHaveCount(0);
  await expect(page.getByRole('region', {name:'Retained state fusion context', exact:true})).toHaveCount(0);
  await expect(page.getByText(/No geometry at this observation/)).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({width:1280,height:1100});
  await page.locator('form').evaluate(element => {(element as HTMLElement).style.display='none';});
  await page.screenshot({path:'docs/engineering/evidence/phase3-timeline.png',fullPage:true});
  await page.locator('form').evaluate(element => {(element as HTMLElement).style.display='';});
  await page.getByLabel('Access token', {exact:true}).fill('invalid');
  await expect(page.getByRole('heading', {name:'Observation points',exact:true})).toHaveCount(0);
  await page.getByRole('button', {name:'Load exact timeline',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'Access denied for this timeline context.'})).toBeVisible();
  writeFileSync('docs/engineering/evidence/phase3-browser.json', JSON.stringify({result:'passed',scope:'Actual Chromium/WebGL over explicitly synthetic private fixtures only',checks:[{command:'Playwright phase3-timeline.spec.ts',exit_code:0}],assertions:{saved_scenario_review:true,published_three_followups:true,actual_webgl:true,camera:true,exact_state_fusion:true,full_window_trends:true,irregular_time_axis:true,selection_clears_old_geometry:true,unauthorized_recovery:true,mobile_overflow:false},limitations:['No authentic observed baseline, clinical validity or browser-driven worker generation claim'],recorded_at:new Date().toISOString()},null,2)+'\n');
});
